@dashboard_bp.route("/services", methods=["POST"])
def create_service() -> tuple[dict[str, Any], int]:
    """Assign/create a new contracted service.
    
    Returns:
        Tuple of response dictionary and HTTP status code.
        
    Raises:
        ValueError: If request data is empty or invalid.
    """
    try:
        data = request.get_json()
        if not data:
            raise ValueError("Service data cannot be empty")
        
        required_fields = ["name", "client"]
        for field in required_fields:
            if field not in data:
                raise ValueError(f"Missing required field: {field}")
        
        new_service = {
            "id": 4,  # In real implementation, this would be generated by database
            "name": data.get("name"),
            "client": data.get("client"),
            "status": data.get("status", "pending"),
            "start_date": data.get("start_date"),
            "end_date": data.get("end_date"),
            "monthly_cost": float(data.get("monthly_cost", 0)) if data.get("monthly_cost") else 0.0,
            "description": data.get("description", ""),
        }
        return jsonify({"service": new_service, "status": "success"}), 201
    except ValueError as e:
        return jsonify({"error": str(e), "status": "error"}), 400
    except Exception as e:
        return jsonify({"error": str(e), "status": "error"}), 500


@dashboard_bp.route("/services/<int:service_id>", methods=["PUT"])
def update_service(service_id: int) -> tuple[dict[str, Any], int]:
    """Edit/update an existing contracted service.
    
    Args:
        service_id: ID of the service to update.
        
    Returns:
        Updated service data.
        
    Raises:
        ValueError: If update data is empty.
    """
    try:
        data = request.get_json()
        if not data:
            raise ValueError("Update data cannot be empty")
        
        updated_service = {
            "id": service_id,
            "name": data.get("name"),
            "client": data.get("client"),
            "status": data.get("status"),
            "start_date": data.get("start_date"),
            "end_date": data.get("end_date"),
            "monthly_cost": float(data.get("monthly_cost", 0)) if data.get("monthly_cost") is not None else None,
            "description": data.get("description"),
        }
        return jsonify({"service": updated_service, "status": "success"})
    except ValueError as e:
        return jsonify({"error": str(e), "status": "error"}), 400
    except Exception as e:
        return jsonify({"error": str(e), "status": "error"}), 500


@dashboard_bp.route("/services/<int:service_id>", methods=["DELETE"])
def delete_service(service_id: int) -> tuple[dict[str, Any], int]:
    """Cancel a contracted service.
    
    Args:
        service_id: ID of the service to cancel.
        
    Returns:
        Tuple of response dictionary and HTTP status code.
    """
    try:
        return jsonify(
            {
                "message": f"Service {service_id} cancelled successfully", 
                "service_id": service_id,
                "status": "cancelled"
            }
        ), 200
    except Exception as e:
        return jsonify({"error": str(e), "status": "error"}), 500


